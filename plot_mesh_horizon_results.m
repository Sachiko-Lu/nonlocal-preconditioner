function plot_mesh_horizon_results(results,outputDir)
paths=["constant","increasing","decreasing"];
labels={'(a) Constant $\delta/h$','(b) Increasing $\delta/h$', ...
    '(c) Decreasing $\delta/h$'};
style=struct('width',7.0,'height',2.70,'font',9.5,'line',1.0, ...
    'marker',4.5,'ink',[0 0 0]);
fig=figure('Visible','off','Units','inches', ...
    'Position',[1 1 style.width style.height],'Color','w', ...
    'Renderer','painters','InvertHardcopy','off');
positions={[0.070 0.285 0.250 0.680],[0.395 0.285 0.250 0.680], ...
    [0.720 0.285 0.250 0.680]};
top=ceil(5*max(results.lambda_max))/5;
allN=unique(results.n_dof);
xLimits=[0.75*min(allN),1.30*max(allN)];

for k=1:3
    ax=axes(fig,'Units','normalized','Position',positions{k}, ...
        'FontName','Times New Roman','FontSize',style.font, ...
        'LineWidth',1,'Box','on','TickDir','in', ...
        'TickLabelInterpreter','latex','XColor','k','YColor','k', ...
        'Color','w','XGrid','off','YGrid','off','Layer','top');
    hold(ax,'on');
    T=sortrows(results(results.path==paths(k),:),'n_dof');
    p1=plot(ax,T.n_dof,T.lambda_min,'-o','Color',style.ink, ...
        'LineWidth',style.line,'MarkerSize',style.marker,'MarkerFaceColor','w');
    p2=plot(ax,T.n_dof,T.lambda_max,'--s','Color',style.ink, ...
        'LineWidth',style.line,'MarkerSize',style.marker,'MarkerFaceColor','w');
    set(ax,'XScale','log','XLim',xLimits,'XTick',allN, ...
        'XTickLabel',cellstr(string(allN)),'YLim',[0 top]);
    xlabel(ax,'$N_h$','Interpreter','latex');
    ylabel(ax,'Eigenvalue','Interpreter','latex');
    legend(ax,[p1 p2],{'$\lambda_{\min}$','$\lambda_{\max}$'}, ...
        'Interpreter','latex','FontSize',style.font-0.5, ...
        'Location','south','NumColumns',2,'Box','off');
    annotation(fig,'textbox',[positions{k}(1),0.005,positions{k}(3),0.10], ...
        'String',labels{k},'Interpreter','latex','FontSize',style.font, ...
        'HorizontalAlignment','center','VerticalAlignment','middle', ...
        'EdgeColor','none','Margin',0);
end

set(fig,'PaperUnits','inches','PaperPositionMode','manual', ...
    'PaperPosition',[0 0 style.width style.height], ...
    'PaperSize',[style.width style.height]);
print(fig,fullfile(outputDir,'figure_6_1.pdf'),'-dpdf','-painters');
print(fig,fullfile(outputDir,'figure_6_1.png'),'-dpng','-r600');
close(fig);
end
